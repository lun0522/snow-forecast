"""Step 2: Fetch multi-model forecasts, NWS gridpoints, MET Norway, and SNOTEL/CDEC telemetry."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from app.fetchers.cdec import fetch_cdec_station_data
from app.fetchers.met_no import fetch_met_no_forecast
from app.fetchers.nws import fetch_grid_forecast
from app.fetchers.open_meteo import DEFAULT_MODELS, fetch_multi_model_forecast
from app.fetchers.snotel import fetch_snotel_data
from app.http_client import HttpFetchError

DEFAULT_RESORTS_PATH = Path(__file__).resolve().parent.parent / "resorts.json"
DEFAULT_SNAPSHOT_PATH = Path(__file__).resolve().parents[2] / "data" / "latest_snapshot.json"


def load_resorts(path: Path = DEFAULT_RESORTS_PATH) -> list[dict[str, Any]]:
    """Load enriched resort configuration generated by Step 1."""
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Run 'python3 -m app.scripts.discover_stations' first."
        )
    doc = json.loads(path.read_text(encoding="utf-8"))
    return doc["resorts"]


def fetch_all_data(
    resorts: list[dict[str, Any]],
    bands: tuple[str, ...] = ("base", "mid", "summit"),
    models: tuple[str, ...] = DEFAULT_MODELS,
    snotel_days: int = 7,
) -> dict[str, Any]:
    """Fetch forecasts (Open-Meteo, MET Norway, NWS) and observations (SNOTEL, CDEC)."""
    triplets: list[str] = []
    seen_triplets: set[str] = set()
    cdec_ids: list[str] = []
    seen_cdec: set[str] = set()

    for resort in resorts:
        for st in resort.get("snotel_stations", [])[:2]:
            t = st.get("triplet")
            if t and t not in seen_triplets:
                seen_triplets.add(t)
                triplets.append(t)
        for cid in resort.get("cdec_candidates", []):
            if cid and cid not in seen_cdec:
                seen_cdec.add(cid)
                cdec_ids.append(cid)

    snotel_by_triplet: dict[str, Any] = {}
    if triplets:
        try:
            snotel_by_triplet = fetch_snotel_data(triplets, days_back=snotel_days, duration="HOURLY")
        except HttpFetchError as exc:
            print(f"[warn] SNOTEL hourly fetch failed ({exc}); falling back to DAILY")
            snotel_by_triplet = fetch_snotel_data(triplets, days_back=snotel_days, duration="DAILY")

    cdec_by_id: dict[str, Any] = {}
    for cid in cdec_ids:
        cdec_by_id[cid] = fetch_cdec_station_data(cid, days_back=snotel_days, duration="D")

    open_meteo_unreachable_error: str | None = None
    resort_snapshots: list[dict[str, Any]] = []

    for resort in resorts:
        band_forecasts: dict[str, Any] = {}
        for band_key in bands:
            band = resort["bands"][band_key]

            # 1. Open-Meteo multi-model (skip remaining calls in this run if host times out)
            if open_meteo_unreachable_error is not None:
                om_data: dict[str, Any] = {"status": "unavailable", "error": open_meteo_unreachable_error}
            else:
                try:
                    om_data = fetch_multi_model_forecast(
                        lat=band["lat"],
                        lon=band["lon"],
                        elevation_m=band["reported_elevation_m"],
                        models=models,
                        forecast_days=10,
                        timeout=6.0,
                        retries=1,
                    )
                    om_data["status"] = "ok"
                except HttpFetchError as exc:
                    open_meteo_unreachable_error = str(exc)
                    print(f"[warn] Open-Meteo unreachable ({exc}); skipping Open-Meteo for remaining bands.")
                    om_data = {"status": "unavailable", "error": open_meteo_unreachable_error}

            # 2. MET Norway Locationforecast 2.0 (ECMWF-backed, altitude-adjusted)
            try:
                met_data: dict[str, Any] = fetch_met_no_forecast(
                    lat=band["lat"],
                    lon=band["lon"],
                    elevation_m=band["reported_elevation_m"],
                )
                met_data["status"] = "ok"
            except HttpFetchError as exc:
                met_data = {"status": "unavailable", "error": str(exc)}

            # 3. NWS 2.5km Gridpoints (NDFD / NBM + forecaster snowLevel)
            nws_data = None
            nws_url = (band.get("nws") or {}).get("forecast_grid_data_url")
            if nws_url:
                try:
                    nws_data = fetch_grid_forecast(nws_url)
                    nws_data["status"] = "ok"
                except HttpFetchError as exc:
                    nws_data = {"status": "unavailable", "error": str(exc)}

            band_forecasts[band_key] = {
                "label": band["label"],
                "elevation_ft": band["reported_elevation_ft"],
                "open_meteo": om_data,
                "met_no": met_data,
                "nws": nws_data,
            }

        resort_snotel = []
        for st in resort.get("snotel_stations", [])[:2]:
            triplet = st["triplet"]
            obs = snotel_by_triplet.get(triplet) or {}
            resort_snotel.append(
                {
                    "station": st,
                    "summary": obs.get("summary", {}),
                }
            )

        resort_cdec = [
            cdec_by_id[cid]
            for cid in resort.get("cdec_candidates", [])
            if cid in cdec_by_id and cdec_by_id[cid].get("observations")
        ]

        resort_snapshots.append(
            {
                "id": resort["id"],
                "name": resort["name"],
                "region": resort["region"],
                "state": resort["state"],
                "bands": band_forecasts,
                "observations": {
                    "snotel": resort_snotel,
                    "cdec": resort_cdec,
                },
            }
        )

    return {
        "fetched_at_utc": datetime.now(timezone.utc).isoformat(),
        "models_requested": list(models),
        "resorts": resort_snapshots,
        "raw_snotel": snotel_by_triplet,
    }


def _fmt(val: float | int | None, suffix: str = "") -> str:
    if val is None:
        return "-"
    return f"{val}{suffix}"


def _fmt_temp_range(win: dict[str, Any]) -> str:
    if win.get("temp_min_f") is None:
        return "-"
    return f"{win['temp_min_f']}/{win['temp_max_f']}°F"


def print_snapshot_report(snapshot: dict[str, Any]) -> None:
    """Print a compact OpenSnow-style multi-model + SNOTEL comparison in the terminal."""
    print(f"\nSnapshot fetched at {snapshot['fetched_at_utc']}")
    print("=" * 96)

    for resort in snapshot["resorts"]:
        print(f"\n{resort['name']} ({resort['region']}, {resort['state']})")
        print("-" * 96)

        for st_entry in resort["observations"]["snotel"]:
            meta = st_entry["station"]
            s = st_entry["summary"]
            if not s:
                print(f"  SNOTEL {meta['triplet']} ({meta['name']}, {meta['elevation_ft']:.0f} ft): no recent obs")
                continue
            print(
                f"  SNOTEL {meta['triplet']} {meta['name']} ({meta['elevation_ft']:.0f} ft, "
                f"{meta['distance_mi']} mi): "
                f"Depth={_fmt(s.get('snow_depth_in'), '\"')} (24h {_fmt(s.get('snow_depth_delta_24h_in'), '\"')}), "
                f"SWE={_fmt(s.get('swe_in'), '\"')} (24h {_fmt(s.get('swe_delta_24h_in'), '\"')}), "
                f"Temp={_fmt(s.get('temp_f'), '°F')} @ {s.get('latest_timestamp')}"
            )

        for cdec in resort["observations"]["cdec"]:
            latest = cdec.get("latest") or {}
            print(
                f"  CDEC {cdec['station_id']}: "
                f"Depth={_fmt(latest.get('snow_depth_in'), '\"')}, "
                f"SWE={_fmt(latest.get('swe_in'), '\"')} @ {latest.get('timestamp')}"
            )

        for band_key in ("base", "mid", "summit"):
            if band_key not in resort["bands"]:
                continue
            band = resort["bands"][band_key]
            print(f"\n  [{band_key.upper()} - {band['elevation_ft']} ft]")
            print(
                f"  {'Source / Model':<20} {'Horizon':>7} {'24h Snow':>10} {'72h Snow':>10} "
                f"{'7d Snow':>10} {'72h QPF':>9} {'72h Temp':>14}"
            )

            om = band.get("open_meteo") or {}
            if om.get("status") == "ok":
                for model_name, mdata in om["models"].items():
                    summary = mdata["summary"]
                    win = summary["windows"]
                    h24, h72, h168 = win.get("24h", {}), win.get("72h", {}), win.get("168h", {})
                    print(
                        f"  {model_name:<20} "
                        f"{summary['max_horizon_hours']:>5}h  "
                        f"{_fmt(h24.get('snowfall_in'), '\"'):>10} "
                        f"{_fmt(h72.get('snowfall_in'), '\"'):>10} "
                        f"{_fmt(h168.get('snowfall_in'), '\"'):>10} "
                        f"{_fmt(h72.get('precip_in'), '\"'):>9} "
                        f"{_fmt_temp_range(h72):>14}"
                    )
            else:
                print(f"  {'open-meteo':<20} {'down':>7}  (unavailable on this network)")

            met = band.get("met_no") or {}
            if met.get("status") == "ok":
                m_win = met["windows"]
                h24, h72, h168 = m_win.get("24h", {}), m_win.get("72h", {}), m_win.get("168h", {})
                print(
                    f"  {'met_no (ECMWF+alt)':<20} "
                    f"{met['max_horizon_hours']:>5}h  "
                    f"{_fmt(h24.get('est_snow_in'), '\"'):>10} "
                    f"{_fmt(h72.get('est_snow_in'), '\"'):>10} "
                    f"{_fmt(h168.get('est_snow_in'), '\"'):>10} "
                    f"{_fmt(h72.get('precip_in'), '\"'):>9} "
                    f"{_fmt_temp_range(h72):>14}"
                )

            nws = band.get("nws") or {}
            if nws.get("status") == "ok":
                nw_win = nws["windows"]
                h24, h72, h168 = nw_win.get("24h", {}), nw_win.get("72h", {}), nw_win.get("168h", {})
                sl_info = ""
                if h72.get("snow_level_min_ft") is not None:
                    sl_info = f" (SnowLvl {h72['snow_level_min_ft']}-{h72['snow_level_max_ft']} ft)"
                print(
                    f"  {'nws_gridpoints':<20} {'~168h':>7} "
                    f"{_fmt(h24.get('snowfall_in'), '\"'):>10} "
                    f"{_fmt(h72.get('snowfall_in'), '\"'):>10} "
                    f"{_fmt(h168.get('snowfall_in'), '\"'):>10} "
                    f"{_fmt(h72.get('precip_in'), '\"'):>9} "
                    f"{_fmt_temp_range(h72):>14}{sl_info}"
                )


def main() -> None:
    parser = argparse.ArgumentParser(description="Fetch live ski resort forecasts & telemetry.")
    parser.add_argument(
        "--resort",
        help="Optional resort id filter (e.g. northstar, heavenly, kirkwood, park-city, keystone)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_SNAPSHOT_PATH,
        help="Path to write full normalized JSON snapshot.",
    )
    args = parser.parse_args()

    resorts = load_resorts()
    if args.resort:
        resorts = [r for r in resorts if r["id"] == args.resort]
        if not resorts:
            raise SystemExit(f"Unknown resort id: {args.resort}")

    snapshot = fetch_all_data(resorts)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
    print_snapshot_report(snapshot)
    print(f"\nSaved full JSON snapshot to {args.output}")


if __name__ == "__main__":
    main()
